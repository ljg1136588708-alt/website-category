  doubao: 'Bytedance',
  kimi: 'Moonshotai',
  aliyun: 'Alibabacloud',
  neteasemusic: 'Neteasecloudmusic',
  hoyoverse: 'Mihoyo',
  removebg: 'Removedotbg',
  capcut: 'Bytedance',
